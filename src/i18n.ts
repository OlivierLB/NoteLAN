export function resolveLocale(obsidianLocale: string | undefined | null): Locale {
  return obsidianLocale?.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function translate(locale: Locale, key: TranslationKey, values: TranslationValues = {}): string {
  const template = locale === "fr" ? FR_MESSAGES[key] : EN_MESSAGES[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}

export function formatCount(locale: Locale, count: number, singular: TranslationKey, plural: TranslationKey): string {
  return `${count} ${translate(locale, count === 1 ? singular : plural)}`;
}
